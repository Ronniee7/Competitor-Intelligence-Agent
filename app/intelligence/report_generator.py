
from app.models.intelligence import CompetitorIntelligence


def generate_markdown_report(
    intelligence: CompetitorIntelligence,
) -> str:

    lines = [
        f"# Competitive Intelligence Report: {intelligence.company_name}",
        "",
        f"**Industry:** {intelligence.industry}",
        "",
        "## Company Overview",
        intelligence.company_description,
        "",
    ]

    categories = {
        "Products and Services": intelligence.products_and_services,
        "Target Customers": intelligence.target_customers,
        "Value Propositions": intelligence.value_propositions,
        "Geographic Markets": intelligence.geographic_markets,
        "Potential Competitive Advantages": (
            intelligence.potential_competitive_advantages
        ),
    }

    for title, findings in categories.items():

        lines.extend([
            f"## {title}",
            "",
        ])

        if not findings:
            lines.extend([
                "No supported findings available.",
                "",
            ])
            continue

        for finding in findings:

            status = (
                "Verified against source text"
                if finding.verified
                else "Unverified"
            )

            lines.extend([
                f"### {finding.claim}",
                "",
                f"- Evidence: {finding.evidence}",
                f"- Source: {finding.source_url}",
                f"- Confidence estimate: {finding.confidence:.2f}",
                f"- Verification: {status}",
                "",
            ])

    lines.extend([
        "## Information Gaps",
        "",
    ])

    information_gaps = intelligence.information_gaps or []

    if information_gaps:
        for gap in information_gaps:
            lines.append(f"- {gap}")
    else:
        lines.append("No information gaps recorded.")

    lines.extend([
        "",
        "---",
        "Generated by Competitor Intelligence Agent.",
    ])

    return "\n".join(lines)
